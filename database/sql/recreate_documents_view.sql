DROP VIEW IF EXISTS documents;

CREATE VIEW documents AS
            SELECT
                (wp.id COLLATE utf8mb4_unicode_ci) AS id,
                (wp.user_id COLLATE utf8mb4_unicode_ci) AS user_id,
                (wp.period_id COLLATE utf8mb4_unicode_ci) AS period_id,
                ('weekly_plan' COLLATE utf8mb4_unicode_ci) AS type,
                NULL AS file_path,
                NULL AS attachment,
                NULL AS month,
                NULL AS year,
                (wp.title COLLATE utf8mb4_unicode_ci) AS title,
                NULL AS file_size,
                NULL AS original_filename,
                NULL AS content,
                (wp.main_target COLLATE utf8mb4_unicode_ci) AS main_target,
                NULL AS target_accomplished,
                NULL AS target_explanation,
                (wp.state COLLATE utf8mb4_unicode_ci) AS state,
                (wp.review_rejection_reason COLLATE utf8mb4_unicode_ci) AS review_rejection_reason,
                (wp.budget_review_status COLLATE utf8mb4_unicode_ci) AS budget_review_status,
                (wp.budget_reviewed_by COLLATE utf8mb4_unicode_ci) AS budget_reviewed_by,
                wp.budget_reviewed_at AS budget_reviewed_at,
                wp.budget_provided_amount AS budget_provided_amount,
                (wp.budget_review_note COLLATE utf8mb4_unicode_ci) AS budget_review_note,
                NULL AS budget_review_items,
                wp.created_at AS created_at,
                wp.updated_at AS updated_at,
                wp.deleted_at AS deleted_at
            FROM weekly_plans wp
            UNION ALL
            SELECT
                (wr.id COLLATE utf8mb4_unicode_ci) AS id,
                (wr.user_id COLLATE utf8mb4_unicode_ci) AS user_id,
                (wr.period_id COLLATE utf8mb4_unicode_ci) AS period_id,
                ('weekly_report' COLLATE utf8mb4_unicode_ci) AS type,
                NULL AS file_path,
                NULL AS attachment,
                NULL AS month,
                NULL AS year,
                (wr.title COLLATE utf8mb4_unicode_ci) AS title,
                NULL AS file_size,
                NULL AS original_filename,
                NULL AS content,
                NULL AS main_target,
                wr.target_accomplished AS target_accomplished,
                (wr.target_explanation COLLATE utf8mb4_unicode_ci) AS target_explanation,
                (wr.state COLLATE utf8mb4_unicode_ci) AS state,
                (wr.review_rejection_reason COLLATE utf8mb4_unicode_ci) AS review_rejection_reason,
                NULL AS budget_review_status,
                NULL AS budget_reviewed_by,
                NULL AS budget_reviewed_at,
                NULL AS budget_provided_amount,
                NULL AS budget_review_note,
                NULL AS budget_review_items,
                wr.created_at AS created_at,
                wr.updated_at AS updated_at,
                wr.deleted_at AS deleted_at
            FROM weekly_reports wr
            UNION ALL
            SELECT
                (mr.id COLLATE utf8mb4_unicode_ci) AS id,
                (mr.user_id COLLATE utf8mb4_unicode_ci) AS user_id,
                NULL AS period_id,
                ('monthly_report' COLLATE utf8mb4_unicode_ci) AS type,
                (mr.file_path COLLATE utf8mb4_unicode_ci) AS file_path,
                (mr.attachment COLLATE utf8mb4_unicode_ci) AS attachment,
                mr.month AS month,
                mr.year AS year,
                (mr.title COLLATE utf8mb4_unicode_ci) AS title,
                mr.file_size AS file_size,
                (mr.original_filename COLLATE utf8mb4_unicode_ci) AS original_filename,
                NULL AS content,
                NULL AS main_target,
                NULL AS target_accomplished,
                NULL AS target_explanation,
                (mr.state COLLATE utf8mb4_unicode_ci) AS state,
                NULL AS review_rejection_reason,
                NULL AS budget_review_status,
                NULL AS budget_reviewed_by,
                NULL AS budget_reviewed_at,
                NULL AS budget_provided_amount,
                NULL AS budget_review_note,
                NULL AS budget_review_items,
                mr.created_at AS created_at,
                mr.updated_at AS updated_at,
                mr.deleted_at AS deleted_at
            FROM monthly_reports mr
            UNION ALL
            SELECT
                (al.id COLLATE utf8mb4_unicode_ci) AS id,
                (al.user_id COLLATE utf8mb4_unicode_ci) AS user_id,
                (al.period_id COLLATE utf8mb4_unicode_ci) AS period_id,
                ('action_log' COLLATE utf8mb4_unicode_ci) AS type,
                NULL AS file_path,
                NULL AS attachment,
                NULL AS month,
                NULL AS year,
                (al.title COLLATE utf8mb4_unicode_ci) AS title,
                NULL AS file_size,
                NULL AS original_filename,
                NULL AS content,
                NULL AS main_target,
                NULL AS target_accomplished,
                NULL AS target_explanation,
                (al.state COLLATE utf8mb4_unicode_ci) AS state,
                NULL AS review_rejection_reason,
                NULL AS budget_review_status,
                NULL AS budget_reviewed_by,
                NULL AS budget_reviewed_at,
                NULL AS budget_provided_amount,
                NULL AS budget_review_note,
                NULL AS budget_review_items,
                al.created_at AS created_at,
                al.updated_at AS updated_at,
                al.deleted_at AS deleted_at
            FROM action_logs al;